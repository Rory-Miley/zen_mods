#!/usr/bin/env zsh
set -euo pipefail

# Root of the zen_mods repository
REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ZEN_PROFILES_DIR="${HOME}/Library/Application Support/zen/Profiles"

# Find active Zen profile (defaults to *.Default (release))
if [[ -z "${ZEN_PROFILE:-}" ]]; then
  ZEN_PROFILE="$(find "$ZEN_PROFILES_DIR" -maxdepth 1 -type d -name "*.Default (release)" | head -n 1)"
fi

if [[ -z "$ZEN_PROFILE" || ! -d "$ZEN_PROFILE" ]]; then
  echo "Error: Could not find Zen profile directory in: $ZEN_PROFILES_DIR" >&2
  echo "Set ZEN_PROFILE=\"/path/to/profile\" and try again." >&2
  exit 1
fi

CHROME_DIR="${ZEN_PROFILE}/chrome"
THEMES_DIR="${CHROME_DIR}/zen-themes"
THEMES_JSON="${ZEN_PROFILE}/zen-themes.json"
THEMES_CSS="${CHROME_DIR}/zen-themes.css"

mkdir -p "$THEMES_DIR"
[[ -f "$THEMES_JSON" ]] || echo "{}" > "$THEMES_JSON"

echo "Target Zen Profile: $ZEN_PROFILE"

# Copy each mod's chrome.css & theme.json into chrome/zen-themes/<id>/
# and merge its manifest entry into zen-themes.json
python3 - "$REPO_ROOT" "$THEMES_DIR" "$THEMES_JSON" "$THEMES_CSS" "$@" <<'PYEOF'
import json
import os
import shutil
import sys
from datetime import datetime

repo_root, themes_dir, themes_json_path, themes_css_path = sys.argv[1:5]
filter_mods = set(sys.argv[5:])

try:
    with open(themes_json_path, "r", encoding="utf-8") as f:
        installed_themes = json.load(f)
except Exception:
    installed_themes = {}

for entry in sorted(os.listdir(repo_root)):
    mod_dir = os.path.join(repo_root, entry)
    if not os.path.isdir(mod_dir) or entry.startswith(".") or entry == "dev":
        continue
    if filter_mods and entry not in filter_mods:
        continue

    theme_json_file = os.path.join(mod_dir, "theme.json")
    chrome_css_file = os.path.join(mod_dir, "chrome.css")
    if not (os.path.isfile(theme_json_file) and os.path.isfile(chrome_css_file)):
        continue

    with open(theme_json_file, "r", encoding="utf-8") as f:
        manifest = json.load(f)

    mod_id = manifest.get("id", entry)
    manifest["id"] = mod_id
    manifest.setdefault("enabled", True)

    # 1. Copy chrome.css and theme.json into <Profile>/chrome/zen-themes/<mod_id>/
    dest_mod_dir = os.path.join(themes_dir, mod_id)
    os.makedirs(dest_mod_dir, exist_ok=True)
    shutil.copy2(chrome_css_file, os.path.join(dest_mod_dir, "chrome.css"))
    shutil.copy2(theme_json_file, os.path.join(dest_mod_dir, "theme.json"))
    readme_file = os.path.join(mod_dir, "README.md")
    if os.path.isfile(readme_file):
        shutil.copy2(readme_file, os.path.join(dest_mod_dir, "readme.md"))

    # 2. Register/update mod in <Profile>/zen-themes.json
    existing = installed_themes.get(mod_id, {})
    if "enabled" in existing:
        manifest["enabled"] = existing["enabled"]
    installed_themes[mod_id] = manifest
    print(f"  ✓ Synced mod '{manifest.get('name', mod_id)}' ({mod_id}) -> {dest_mod_dir}")

with open(themes_json_path, "w", encoding="utf-8") as f:
    json.dump(installed_themes, f, indent=2)

# 3. Rebuild <Profile>/chrome/zen-themes.css from all enabled mods
lines = [
    "/* Zen Mods - Generated by zen_mods/dev/sync-mods.sh",
    f"* FILE GENERATED AT: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
    "*/",
    "",
]
for mod_id, mod_info in installed_themes.items():
    if not mod_info.get("enabled", True):
        continue
    mod_css_path = os.path.join(themes_dir, mod_id, "chrome.css")
    if os.path.isfile(mod_css_path):
        lines.append(f"/* Name: {mod_info.get('name', mod_id)} */")
        lines.append(f"/* Description: {mod_info.get('description', '')} */")
        lines.append(f"/* Author: @{mod_info.get('author', '')} */")
        lines.append("")
        with open(mod_css_path, "r", encoding="utf-8") as css_f:
            lines.append(css_f.read().rstrip())
        lines.append("")

lines.append("/* End of Zen Mods */")
with open(themes_css_path, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")

print(f"  ✓ Updated {themes_json_path}")
print(f"  ✓ Rebuilt {themes_css_path}")
PYEOF

echo ""
echo "Done! To hot-reload in Zen without restarting:"
echo "  Open about:preferences#zenMarketplace and toggle the mod off/on (or restart Zen)."
